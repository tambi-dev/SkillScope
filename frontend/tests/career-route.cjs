const assert = require("node:assert/strict");
const { readFileSync, mkdirSync } = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright");

async function main() {
  const browser = await chromium.launch({ headless: true, args: ["--mute-audio"], channel: process.env.PLAYWRIGHT_CHANNEL || undefined });
  const base = (process.env.SKILLSCOPE_URL || "http://127.0.0.1:8001").replace(/\/$/, "");
  const captures = path.resolve(__dirname, "../../artifacts");
  mkdirSync(captures, { recursive: true });
  const context = await browser.newContext({ viewport: { width: 1366, height: 900 }, reducedMotion: "reduce", colorScheme: "light" });
  await context.addInitScript(() => {
    window.soundStarts = 0;
    const NativeAudioContext = window.AudioContext;
    window.AudioContext = class extends NativeAudioContext { constructor(...args) { super(...args); window.soundStarts++; } };
  });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  const errors = [], sent = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("request", (request) => sent.push(request.url() + (request.postData() || "")));
  const noOverflow = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "The guide must fit the viewport");
  const capture = async (name) => { await noOverflow(); await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" })); await page.screenshot({ path: path.join(captures, name), fullPage: true }); };
  const allFields = () => page.getByRole("button", { name: "See all three fields", exact: true }).click();
  const choose = (field) => page.getByRole("button", { name: `Explore ${field}`, exact: true }).click();
  const start = () => page.getByRole("button", { name: /^(Try this task|Try the task again)$/ }).click();
  try {
    await page.goto(base);
    assert.equal(await page.locator("html").getAttribute("data-theme"), "dark", "New visits default to dark even with a light OS preference");
    await page.getByRole("button", { name: "Switch to light theme" }).click();
    await page.getByRole("heading", { name: "Find an IT field you want to try." }).waitFor();
    assert.equal(await page.locator('.career-field-choice').count(), 3);
    assert.equal(await page.locator('.career-explorer input[type="radio"]').count(), 0, "No abstract interest quiz");
    assert.equal(await page.getByRole("combobox", { name: "Career market" }).count(), 0, "Vacancy controls stay out of the first choice");
    assert.equal(await page.getByRole("button", { name: "Open Mr. Scope assistant" }).count(), 0);
    await capture("beginner-fields-desktop.png");
    await page.setViewportSize({ width: 390, height: 844 });
    await capture("beginner-fields-mobile.png");
    await page.setViewportSize({ width: 1366, height: 900 });
    await choose("Data analysis");
    await page.getByRole("heading", { name: "Data analysis", exact: true }).waitFor();
    assert.ok(await page.getByRole("button", { name: "See all three fields", exact: true }).evaluate((element) => element.getBoundingClientRect().top >= 60), "Back navigation must stay visible below sticky tabs after choosing a field");
    assert.equal(await page.locator('.career-field-choice').count(), 0, "The selected guide replaces the other choices");
    await page.getByText("A data analyst helps a team understand what is happening.", { exact: false }).waitFor();
    await capture("beginner-explanation-desktop.png");

    // Optional data stays accurate and recoverable without blocking the beginner path.
    await page.getByText("What do current vacancies say?", { exact: true }).click();
    await page.locator('.career-evidence-date').waitFor();
    await page.getByRole("combobox", { name: "Career market" }).selectOption("kz");
    const roles = await (await page.request.get(`${base}/api/roles?market=kz`)).json();
    const analyst = roles.items.find((item) => item.code === "data_analyst");
    await page.getByText(`${analyst.vacancies} observed vacancies`, { exact: true }).waitFor();
    await page.getByRole("combobox", { name: "Career market" }).selectOption("tj");
    await page.getByText("No matching vacancies here. This does not mean no hiring; the exercise is still available.").waitFor();
    await page.route("**/api/roles**", (route) => route.fulfill({ status: 503, body: "Unavailable" }));
    await page.getByRole("combobox", { name: "Career market" }).selectOption("tm");
    await page.getByText("Vacancy data could not load. The field guide and task still work.", { exact: false }).waitFor();
    assert.equal(await page.locator('.career-skill-evidence').count(), 0);
    await page.unroute("**/api/roles**");
    await page.getByRole("button", { name: "Retry evidence", exact: true }).click();
    await page.locator('.career-evidence-date').waitFor();
    await start();
    await page.getByRole("heading", { name: "Help a café check its sales", exact: true }).waitFor();
    assert.equal(await page.getByRole("combobox", { name: "Career market" }).count(), 0, "Practice is free of vacancy controls");
    assert.equal(await page.getByRole("button", { name: "Completion sound" }).getAttribute("aria-pressed"), "true", "Sound is enabled by default");
    await page.getByRole("button", { name: "Completion sound" }).click();
    assert.equal(await page.evaluate(() => localStorage.getItem("skillscope-sound")), "off");
    await capture("beginner-data-task-desktop.png");
    await page.getByLabel("Coffee total ($)", { exact: true }).fill("15");
    await page.getByLabel("Tea total ($)", { exact: true }).fill("18");
    await page.getByRole("button", { name: "Check my totals" }).click();
    await page.getByText("Check the order numbers: keep one A04 and every other order. You should have five orders left.").waitFor();
    await page.getByRole("checkbox", { name: "Keep row 5, order A04", exact: true }).uncheck();
    await page.getByRole("button", { name: "Check my totals" }).click();
    await page.getByText("The repeated order is removed. Now add the three Coffee amounts and the two Tea amounts again.").waitFor();
    await page.getByLabel("Tea total ($)", { exact: true }).fill("10");
    await page.getByRole("button", { name: "Check my totals" }).click();
    await page.getByRole("heading", { name: "You found the answer.", exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.soundStarts), 0, "The explicit mute setting prevents playback");
    assert.equal(await page.locator(".task-completion-mark").evaluate((el) => el.getAnimations({ subtree: true }).length), 0, "Reduced motion keeps the static success check");
    await page.locator('.task-completion-mark[data-celebrating="false"]').waitFor();
    await page.getByRole("button", { name: "Check my totals" }).click();
    assert.equal(await page.locator(".task-completion-mark").getAttribute("data-celebrating"), "false", "Rechecking must not replay the celebration");
    await page.getByRole("button", { name: "Choose my next step", exact: true }).click();
    await page.locator('#career-reflection').fill("Checking real rows made this clear.");
    await page.getByRole("button", { name: "Make my next learning plan" }).click();
    const download = page.waitForEvent("download");
    await page.getByRole("button", { name: "Download my plan" }).click();
    const plan = readFileSync(await (await download).path(), "utf8");
    assert.match(plan, /Checking real rows made this clear/);
    assert.match(plan, /weekly expenses/);
    assert.ok(!sent.some((request) => request.includes("Checking real rows")), "Notes must not leave the browser");
    await capture("beginner-next-step-desktop.png");
    await page.reload();
    await page.getByRole("region", { name: "My next step", exact: true }).waitFor();
    assert.equal(await page.locator('#career-reflection').inputValue(), "Checking real rows made this clear.");
    await allFields();

    await choose("Web development"); await start();
    assert.equal(await page.getByRole("button", { name: "Completion sound" }).getAttribute("aria-pressed"), "false", "Explicit mute survives reload and field changes");
    await page.getByRole("button", { name: "Completion sound" }).click();
    assert.equal(await page.evaluate(() => localStorage.getItem("skillscope-sound")), "on");
    await page.emulateMedia({ reducedMotion: "no-preference" });
    const editor = page.getByLabel("Your HTML · edit the words between the tags", { exact: true });
    await editor.fill('<h1>Accidentally removed the rest');
    await page.getByRole("button", { name: "Reset sample", exact: true }).click();
    assert.match(await editor.inputValue(), /<h1>Workshop<\/h1>/);
    assert.match(await editor.inputValue(), /Click here/);
    await editor.fill('<h1>Build your first web page</h1>\n<p>A free introduction.</p>\n<button type="button">Click here</button>');
    await page.getByRole("button", { name: "Update preview" }).click();
    await page.getByText("The heading is correct. Now put Save my place between the <button> tags.").waitFor();
    const finishedHtml = '<h1>Build your first web page</h1>\n<p>A free introduction.</p>\n<button type="button">Save my place</button>';
    await editor.fill(finishedHtml);
    await page.getByRole("button", { name: "Update preview" }).click();
    await page.frameLocator('iframe').getByRole("heading", { name: "Build your first web page" }).waitFor();
    assert.equal(await page.locator('iframe').getAttribute('sandbox'), "");
    await page.getByRole("heading", { name: "Your changes are visible." }).waitFor();
    assert.equal(await page.evaluate(() => window.soundStarts), 1, "Opting in plays a chime on success only");
    assert.ok(await page.locator(".task-completion-mark").evaluate((el) => el.getAnimations({ subtree: true }).length) > 0, "Success animates when motion is allowed");
    await page.getByRole("button", { name: "Update preview" }).click();
    assert.equal(await page.evaluate(() => window.soundStarts), 1, "Repeated checks do not replay sound");
    await page.locator('.task-completion-mark[data-celebrating="false"]').waitFor();
    await capture("beginner-web-task-desktop.png");
    await page.getByRole("button", { name: "Choose my next step" }).click();
    assert.equal(await page.locator('#career-reflection').inputValue(), "", "Notes stay separate by field");
    await allFields();

    await choose("Software testing"); await start();
    assert.equal(await page.getByRole("button", { name: "Completion sound" }).getAttribute("aria-pressed"), "true", "The sound preference carries across tasks");
    await page.emulateMedia({ reducedMotion: "reduce" });
    await page.getByLabel("Age in years", { exact: true }).fill("15");
    await page.getByRole("button", { name: "Test booking", exact: true }).click();
    await page.getByText("Age 15: Booking accepted", { exact: true }).waitFor();
    assert.equal(await page.getByRole("heading", { name: "Describe the age-15 problem" }).count(), 0);
    await page.getByLabel("Age in years", { exact: true }).fill("16");
    await page.getByRole("button", { name: "Test booking", exact: true }).click();
    await page.getByText("Age 16: Booking accepted", { exact: true }).waitFor();
    await page.getByLabel("What should happen when someone enters 15?", { exact: true }).fill("The form should reject the booking.");
    await page.getByLabel("What actually happened when you tested 15?", { exact: true }).fill("The form accepted it.");
    await page.getByRole("button", { name: "Save my observation", exact: true }).click();
    await page.getByRole("heading", { name: "Your observation is saved." }).waitFor();
    await capture("beginner-qa-task-desktop.png");
    await page.setViewportSize({ width: 390, height: 844 });
    await capture("beginner-qa-task-mobile.png");
    await page.setViewportSize({ width: 320, height: 740 });
    await page.getByRole("button", { name: "Switch to Kyrgyz" }).click();
    await page.getByRole("heading", { name: "Катталуу формасынан катаны табыңыз", exact: true }).waitFor();
    await page.getByRole("button", { name: "Караңгы темага өтүү" }).click();
    await capture("beginner-qa-ky-dark.png");
    await page.getByRole("button", { name: "Англисчеге өтүү" }).click();
    await page.goto(`${base}/privacy`);
    await page.getByRole("button", { name: "Clear saved preferences" }).click();
    assert.equal(await page.evaluate(() => localStorage.getItem("skillscope-career-route")), null);
    assert.equal(await page.evaluate(() => localStorage.getItem("skillscope-sound")), null);

    const unavailable = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce" });
    await unavailable.addInitScript(() => { Storage.prototype.getItem = () => { throw new Error("Disabled"); }; Storage.prototype.setItem = () => { throw new Error("Disabled"); }; });
    await unavailable.route("**/api/**", (route) => route.fulfill({ status: 503, body: "Unavailable" }));
    const offline = await unavailable.newPage();
    await offline.goto(base);
    await offline.getByRole("button", { name: "Explore Web development", exact: true }).click();
    await offline.getByRole("button", { name: "Try this task", exact: true }).click();
    await offline.getByLabel("Your HTML · edit the words between the tags", { exact: true }).fill(finishedHtml);
    await offline.getByRole("button", { name: "Update preview" }).click();
    await offline.getByRole("button", { name: "Choose my next step" }).click();
    await offline.getByRole("button", { name: "Make my next learning plan" }).click();
    await offline.getByText("Browser storage is unavailable. Keep this page open or download your plan.").waitFor();
    await offline.getByRole("button", { name: "Download my plan" }).waitFor();
    await unavailable.close();
    assert.deepEqual(errors, []);
    console.log("PASS: no quiz; one field/stage at a time; explanations; all three inline tasks with specific feedback; optional live country data; drafts, plans, privacy, error/retry, unavailable API/storage, EN/KY, light/dark and 1366/390/320px layouts.");
  } finally { await browser.close(); }
}
main().catch((error) => { console.error(error); process.exit(1); });
