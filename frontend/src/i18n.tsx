interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (message: string, values?: Values) => string;
  formatDate: (value: string | null) => string;
  formatCurrency: (value: number, currency: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function savedLanguage(): Language {
  try { return window.localStorage.getItem("skillscope-language") === "ky" ? "ky" : "en"; }
  catch { return "en"; }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(savedLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    document.querySelector('meta[name="description"]')?.setAttribute("content", language === "ky"
      ? "IT багыттарын салыштырып, практикалык тапшырманы сынап, кийинки окуу кадамыңызды тандаңыз."
      : "Compare IT directions, try practical exercises and choose what to learn next, with vacancy evidence from selected markets.");
    try { window.localStorage.setItem("skillscope-language", language); } catch { /* Language still works without storage. */ }
  }, [language]);

  const t = (message: string, values: Values = {}) => {
    const template = language === "ky" ? kyrgyz[message] ?? message : message;
    return template.replace(/\{(\w+)\}/g, (match, key: string) => values[key] === undefined ? match : String(values[key]));
  };

  const formatDate = (value: string | null) => {
    if (!value) return t("date unavailable");
    const date = new Date(value);
    return Number.isNaN(date.valueOf()) ? t("date unavailable") : new Intl.DateTimeFormat(language === "ky" ? "ky-KG" : "en", { dateStyle: "medium" }).format(date);
  };

  const formatCurrency = (value: number, currency: string) => new Intl.NumberFormat(language === "ky" ? "ky-KG" : "en", {
    style: "currency", currency, maximumFractionDigits: 0,
  }).format(value);

  return <LanguageContext.Provider value={{ language, setLanguage, t, formatDate, formatCurrency }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("LanguageProvider is missing");
  return context;
}

export function LanguageSwitch() {
  const { language, setLanguage, t } = useLanguage();
  const next = language === "en" ? "ky" : "en";
  const label = t(next === "ky" ? "Switch to Kyrgyz" : "Switch to English");
  return <button type="button" className="language-switch" aria-label={label} title={label} onClick={() => setLanguage(next)}>
    <span aria-hidden="true">{language === "en" ? "EN" : "КЫ"}</span>
  </button>;
}
